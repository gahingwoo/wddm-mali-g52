# Writes abicheck.c: a program that prints the size of every struct in
# include/maliwddm_abi.h and include/malikm_ioctl.h and the offset of every
# field. These structs cross from the UMD to the 64-bit kernel driver as
# bytes (allocation private data, escapes, the command buffer); a 32-bit UMD
# can only use them if each prints the same on x86 as on ARM64. CI builds
# the program for ARM64, x64 and x86 and compares the three outputs.
#
#   abicheck.py <repo root> <out.c>
#
# Generated rather than written by hand so a field added to a header is
# checked without anyone remembering to list it here.
import os
import re
import sys

root, out = sys.argv[1], sys.argv[2]
headers = ["include/maliwddm_abi.h", "include/malikm_ioctl.h"]
structs = []
for h in headers:
    src = open(os.path.join(root, h), encoding="utf-8").read()
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    src = re.sub(r"//[^\n]*", "", src)
    for m in re.finditer(r"typedef struct (_\w+) \{(.*?)\} (\w+);", src, re.S):
        fields = []
        for decl in m.group(2).split(";"):
            decl = decl.strip()
            if not decl:
                continue
            for f in decl.split(None, 1)[1].split(","):
                fields.append(re.sub(r"\[.*\]", "", f.strip()))
        structs.append((m.group(3), fields))

with open(out, "w", encoding="utf-8") as f:
    f.write("/* Generated by tools/windows/abicheck.py; do not edit. */\n")
    f.write("#include <stddef.h>\n#include <stdio.h>\n")
    f.write('#include "malikm_ioctl.h"\n#include "maliwddm_abi.h"\n\n')
    f.write("int main(void)\n{\n")
    for name, fields in structs:
        f.write('    printf("%s size %%u\\n", (unsigned)sizeof(%s));\n' % (name, name))
        for fl in fields:
            f.write('    printf("%s.%s %%u\\n", (unsigned)offsetof(%s, %s));\n' % (name, fl, name, fl))
    f.write("    return 0;\n}\n")
print("abicheck.c: %d structs, %d fields" % (len(structs), sum(len(x[1]) for x in structs)))
